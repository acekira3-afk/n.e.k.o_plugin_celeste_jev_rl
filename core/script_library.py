    def __init__(self, logger=None):
        self.logger = logger
        self._scripts: dict[str, FrameScript] = {}
        self._usage_stats: dict[str, int] = {}
        self._success_stats: dict[str, int] = {}
        self._load_builtin()

    def _load_builtin(self):
        for entry in self.BUILTIN_SCRIPTS:
            steps = [FrameStep(s["frame"], s["keys"]) for s in entry["steps"]]
            script = FrameScript(
                id=entry["id"],
                name=entry["name"],
                description=entry["description"],
                steps=steps,
                difficulty=entry.get("difficulty", "normal"),
                prerequisites=entry.get("prerequisites", []),
            )
            self._scripts[script.id] = script

    def add_script(self, script: FrameScript):
        self._scripts[script.id] = script

    def get(self, script_id: str) -> FrameScript | None:
        return self._scripts.get(script_id)

    def list_scripts(self) -> list[str]:
        return list(self._scripts.keys())

    def get_options_for_jev(self) -> dict[str, str]:
        """Return script IDs and descriptions for Jev's Choice question."""
        return {
            sid: f"{s.name}: {s.description}"
            for sid, s in self._scripts.items()
        }

    def record_usage(self, script_id: str, success: bool):
        self._usage_stats[script_id] = self._usage_stats.get(script_id, 0) + 1
        if success:
            self._success_stats[script_id] = self._success_stats.get(script_id, 0) + 1

    def get_stats(self) -> dict[str, Any]:
        stats = {}
        for sid in self._scripts:
            uses = self._usage_stats.get(sid, 0)
            succ = self._success_stats.get(sid, 0)
            stats[sid] = {
                "uses": uses,
                "successes": succ,
                "success_rate": succ / uses if uses > 0 else 0,
            }
        return stats

    def export_json(self) -> str:
        data = [s.to_dict() for s in self._scripts.values()]
        return json.dumps(data, indent=2, ensure_ascii=False)
