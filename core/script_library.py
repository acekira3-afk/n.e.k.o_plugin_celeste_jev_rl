"""Frame-precise script library for Celeste gameplay.

Each script is a list of (frame_offset, keys) pairs that replay
human-quality frame-precise inputs. Scripts are triggered by
Jev's situation recognition, not generated frame-by-frame.

This mirrors how speedrunners operate: recognize a pattern,
then execute a muscle-memory sequence.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from typing import Any

KEY_NAMES = ["up", "down", "left", "right", "z", "x", "c"]
KEY_BITS = {name: 1 << i for i, name in enumerate(KEY_NAMES)}


@dataclass
class FrameStep:
    """One frame's input state."""

    frame: int
    keys: list[str]

    @property
    def bitmask(self) -> int:
        mask = 0
        for k in self.keys:
            mask |= KEY_BITS.get(k, 0)
        return mask


@dataclass
class FrameScript:
    """A frame-precise input sequence for a specific gameplay situation.

    Example:
        FrameScript(
            id="dash_across_gap",
            name="Dash Across Gap",
            description="Jump then air-dash to cross a gap",
            steps=[
                FrameStep(0, ["right"]),
                FrameStep(4, ["right", "x"]),
                FrameStep(6, ["right"]),
                FrameStep(8, ["right", "z", "up"]),
                FrameStep(11, ["right"]),
                FrameStep(14, []),
            ],
            duration_frames=14,
            target_fps=60,
        )
    """

    id: str
    name: str
    description: str
    steps: list[FrameStep]
    duration_frames: int = 0
    target_fps: int = 60
    difficulty: str = "normal"  # easy / normal / hard / extreme
    prerequisites: list[str] = field(default_factory=list)  # e.g. ["has_dash", "airborne"]

    def __post_init__(self):
        if not self.duration_frames and self.steps:
            self.duration_frames = self.steps[-1].frame + 1

    @property
    def duration_seconds(self) -> float:
        return self.duration_frames / self.target_fps

    def get_input_at_frame(self, frame: int) -> list[str]:
        """Return the keys that should be pressed at a given frame."""
        active = FrameStep(frame, [])
        for step in self.steps:
            if step.frame <= frame:
                active = step
            else:
                break
        return active.keys

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "description": self.description,
            "difficulty": self.difficulty,
            "duration_frames": self.duration_frames,
            "duration_seconds": round(self.duration_seconds, 3),
            "prerequisites": self.prerequisites,
            "steps": [
                {"frame": s.frame, "keys": s.keys} for s in self.steps
            ],
        }


